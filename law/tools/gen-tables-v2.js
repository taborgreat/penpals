// Generates law/v2/tables.js: the curves law v2 adds (oxidation, fading, air,
// surface, dents, wear, sinking, cockling), in the same 50-digit BigInt fixed
// point as v1's tables (gen-tables.js), rounded to integers. v1's tables are
// used as they are.
//
//   node law/tools/gen-tables-v2.js           write law/v2/tables.js
//   node law/tools/gen-tables-v2.js --check   exit 1 if the committed file differs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const PARAMS = {
  OX_N: 512,
  OX_TAU: 32, // OX[x] = 256·(1 − e^(−x/32)): darkness, x in 1/32 of the time constant
  FADE_N: 4096,
  FADE_FLOOR: 64,
  FADE_TAU: 512, // FADE[k] = 64 + 192·e^(−k/512): light never takes all of it
  SURF_TAU: [8, 1], // SURFACE[d] = 256·e^(−d/8): how much light reaches ink sunk d levels
  AIR_DEPTH: [10, 1],
  AIR_POOL: [4, 1],
  AIR_FLOOR: [3, 10], // AIR[d][thick] = 256·(0.3 + 0.7·e^(−d/10)·e^(−thick/4)): air always gets in, slowly
  DENT_BASE: 120,
  DENT_GAMMA: [3, 2], // DENT_Q[p] = 120·(p/255)^(3/2) dentA per ms of pressing
  WEAR_BASE: 5,
  WEAR_GAMMA: [3, 2], // WEAR_Q[p] = 5·(p/153)^(3/2) wearA per moving stamp over a wet cell
  THICK: 24,
  COCKLE_LO: 32,
  COCKLE_HI: 96, // COCKLE[s]: smoothstep from soak 32 to 96, ×256
};

const D = 50n;
const S = 10n ** D;
const fx = (n, d = 1n) => (BigInt(n) * S) / BigInt(d);
const mul = (a, b) => (a * b) / S;
const div = (a, b) => (a * S) / b;

function expFx(x) {
  let k = 0;
  let y = x;
  while (y > S / 8n || y < -S / 8n) {
    y /= 2n;
    k++;
  }
  let sum = S;
  let term = S;
  for (let n = 1n; n < 200n; n++) {
    term = mul(term, y) / n;
    if (term === 0n) break;
    sum += term;
  }
  for (let i = 0; i < k; i++) sum = mul(sum, sum);
  return sum;
}
function atanhFx(x) {
  const x2 = mul(x, x);
  let p = x;
  let sum = 0n;
  for (let n = 1n; n < 2000n; n += 2n) {
    const t = p / n;
    if (t === 0n) break;
    sum += t;
    p = mul(p, x2);
  }
  return sum;
}
const LN2 = 2n * atanhFx(fx(1, 3));
function lnFx(y) {
  let e = 0n;
  let m = y;
  while (m >= 2n * S) {
    m /= 2n;
    e++;
  }
  while (m < S) {
    m *= 2n;
    e--;
  }
  return e * LN2 + 2n * atanhFx(div(m - S, m + S));
}
const powFx = (base, [num, den]) => expFx((lnFx(base) * BigInt(num)) / BigInt(den));
function roundFx(x) {
  const neg = x < 0n;
  const a = neg ? -x : x;
  const r = (a + S / 2n) / S;
  return Number(neg ? -r : r);
}
const ratio = ([n, d]) => fx(n, d);

export function build(p = PARAMS) {
  const t = {};
  // Darkness of oak gall: 256·(1 − e^(−x/OX_TAU)).
  t.OX = Array.from({ length: p.OX_N }, (_, x) => roundFx(256n * (S - expFx(-fx(x, p.OX_TAU)))));
  // Fading by light: what is left, ×256.
  t.FADE = Array.from({ length: p.FADE_N }, (_, k) => p.FADE_FLOOR + roundFx(BigInt(256 - p.FADE_FLOOR) * expFx(-fx(k, p.FADE_TAU))));
  // Light reaching ink sunk d levels into the fibers, ×256.
  t.SURFACE = Array.from({ length: p.THICK + 1 }, (_, d) => roundFx(256n * expFx(-div(fx(d), ratio(p.SURF_TAU)))));
  // Air reaching a cell, ×256, by depth (rows) and pool height (columns).
  t.AIR = Array.from({ length: p.THICK + 1 }, (_, d) =>
    Array.from({ length: 16 }, (_, k) => roundFx(256n * (ratio(p.AIR_FLOOR) + mul(S - ratio(p.AIR_FLOOR), mul(expFx(-div(fx(d), ratio(p.AIR_DEPTH))), expFx(-div(fx(k), ratio(p.AIR_POOL)))))))),
  );
  // Pressing dents the paper: dentA per ms at pressure p.
  t.DENT_Q = Array.from({ length: 256 }, (_, q) => (q === 0 ? 0 : roundFx(BigInt(p.DENT_BASE) * powFx(fx(q, 255), p.DENT_GAMMA))));
  // Working a wet cell wears it: wearA per pass at pressure p.
  t.WEAR_Q = Array.from({ length: 256 }, (_, q) => (q === 0 ? 0 : roundFx(BigInt(p.WEAR_BASE) * powFx(fx(q, 153), p.WEAR_GAMMA))));
  // A soaked cell drying buckles: ridge height ×256 by soak level (smoothstep above COCKLE_MIN).
  t.COCKLE = Array.from({ length: 256 }, (_, s) => {
    if (s <= p.COCKLE_LO) return 0;
    if (s >= p.COCKLE_HI) return 256;
    const u = fx(s - p.COCKLE_LO, p.COCKLE_HI - p.COCKLE_LO);
    return roundFx(256n * (3n * mul(u, u) - 2n * mul(mul(u, u), u)));
  });
  return t;
}

export function render(tables, params = PARAMS) {
  const lines = [
    '// GENERATED by law/tools/gen-tables-v2.js — do not edit. Part of law v2.',
    `// Parameters: ${JSON.stringify(params)}`,
    '// Every value is an integer computed in 50-digit BigInt fixed point.',
    '',
  ];
  for (const [name, value] of Object.entries(tables)) {
    const flat = value.flat();
    const kind = flat.some((v) => v < 0) ? 'Int32Array' : flat.every((v) => v < 65536) ? 'Uint16Array' : 'Uint32Array';
    const rows = Array.isArray(value[0]) ? value[0].length : 0;
    lines.push(`// ${name}${rows ? ` (${value.length} rows × ${rows}, row-major)` : ` (${value.length})`}`);
    lines.push(`export const ${name} = ${kind}.from([`);
    for (let i = 0; i < flat.length; i += 16) lines.push(`  ${flat.slice(i, i + 16).join(', ')},`);
    lines.push(']);');
    lines.push('');
  }
  return lines.join('\n');
}

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'v2', 'tables.js');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(build());
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (now !== text) {
      console.error('law/v2/tables.js differs from what gen-tables-v2.js produces.');
      process.exit(1);
    }
    console.log('v2 tables match');
  } else {
    fs.writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
